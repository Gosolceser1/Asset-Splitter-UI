namespace AssetProcessor;

public static class TemplateBootstrapService
{
    public static string[] BootstrapTemplates(PipelineContext context, string gameType, string customTemplateFile, bool autoTemplates)
    {
        if (context.DebugMode)
        {
            context.Log.Write(ConsoleMessageKind.Templates, ConsoleMessages.Get("templatesCheckingUpdate"));
        }

        try
        {
            if (File.Exists(Path.Combine(context.SourceXmlFolder, "templates.xml")))
            {
                if (TemplateExtractor.NeedsUpdate(context.SourceXmlFolder, gameType))
                {
                    string templateConfigPath = TemplateLoader.GetTemplateConfigPath(gameType);
                    bool allowAutoUpdate = TemplateLoader.IsAutoGeneratedTemplateList(templateConfigPath);
                    if (allowAutoUpdate)
                    {
                        context.Log.WriteLocalized(ConsoleMessageKind.Info, "autoUpdateUpdating", always: true);
                        int count = TemplateExtractor.ExtractAndUpdateTemplates(context.SourceXmlFolder, gameType);
                        if (count > 0)
                        {
                            context.Log.WriteLocalized(ConsoleMessageKind.Ok, "autoUpdateListUpdated", always: true, count);
                        }
                        else
                        {
                            context.Log.WriteLocalized(ConsoleMessageKind.Warning, "autoUpdateReturnedZero", always: true);
                        }
                    }
                    else
                    {
                        context.Log.WriteLocalized(ConsoleMessageKind.Warning, "autoUpdateSkipped", always: true);
                    }
                }
                else if (context.DebugMode)
                {
                    context.Log.Write(ConsoleMessageKind.Ok, ConsoleMessages.Get("templatesAlreadyUpToDate"));
                }
            }
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or System.Xml.XmlException)
        {
            context.Log.WriteLocalized(ConsoleMessageKind.Warning, "autoUpdateFailed", always: true, ex.Message);
            context.Log.WriteLocalized(ConsoleMessageKind.Info, "continuingExistingTemplateConfig", always: true);
        }

        try
        {
            string[] templateList;
            if (autoTemplates)
            {
                context.Log.WriteLocalized(ConsoleMessageKind.Info, "autoTemplatesExtractingAll", always: true);
                // templates.xml lives inside an RDA archive in the game install; Phase 1 extracts it
                // into source_xml. Only fall back to searching AssetRoot for loose-file setups.
                string sourceTemplatesXml = Path.Combine(context.SourceXmlFolder, "templates.xml");
                string templatesXmlPath = File.Exists(sourceTemplatesXml)
                    ? sourceTemplatesXml
                    : TemplateExtractor.FindTemplatesXml(context.AssetRoot);
                HashSet<string> allTemplates = string.IsNullOrEmpty(templatesXmlPath)
                    ? []
                    : TemplateExtractor.ExtractTemplatesFromXml(templatesXmlPath);
                if (allTemplates.Count > 0)
                {
                    templateList = [.. allTemplates.OrderBy(t => t)];
                    context.Log.WriteLocalized(ConsoleMessageKind.Ok, "autoTemplatesFound", always: true, templateList.Length);
                }
                else
                {
                    context.Log.WriteLocalized(ConsoleMessageKind.Warning, "autoTemplatesNoneFound", always: true);
                    templateList = TemplateLoader.LoadTemplates(gameType, customTemplateFile);
                }
            }
            else
            {
                templateList = TemplateLoader.LoadTemplates(gameType, customTemplateFile);
            }

            if (context.DebugMode)
            {
                context.Log.WriteLocalized(ConsoleMessageKind.Ok, "configReadyWithTemplates", always: true, templateList.Length);
                context.Log.Debug(string.Format(ConsoleMessages.Get("debugTemplateListPath"), TemplateLoader.GetTemplateConfigPath(gameType)));
                context.Log.Debug(string.Format(ConsoleMessages.Get("debugTemplateFixlistCount"), TemplateLoader.LoadFixlist(gameType, context.CustomFixlistFile).Length));
            }

            return templateList;
        }
        catch (Exception ex)
        {
            context.Log.WriteLocalized(ConsoleMessageKind.Error, "failedToLoadTemplates", always: true, ex.Message);
            throw new InvalidOperationException("Failed to load templates.", ex);
        }
    }
}
