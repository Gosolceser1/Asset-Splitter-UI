using System.Xml;
using AssetProcessor;

namespace AssetSplitter.Tests;

public sealed class GauntletFixRegressionTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "as-fix-" + Guid.NewGuid().ToString("N"));

    public GauntletFixRegressionTests()
    {
        Directory.CreateDirectory(_root);
    }

    public void Dispose()
    {
        try
        {
            if (Directory.Exists(_root))
            {
                Directory.Delete(_root, recursive: true);
            }
        }
        catch (IOException)
        {
        }
        catch (UnauthorizedAccessException)
        {
        }
    }

    [Fact]
    public void CombineSourceXml_DoesNotRequireTrailingSeparator()
    {
        string folder = Path.Combine(_root, "source_xml");
        Directory.CreateDirectory(folder);
        var context = new PipelineContext { SourceXmlFolder = folder };
        string combined = AssetProcessorFileSystem.CombineSourceXml(context, "assets.xml");
        Assert.Equal(Path.Combine(folder, "assets.xml"), combined);
    }

    [Fact]
    public void ExtractSingleAsset_QuotedBaseAssetGuid_DoesNotThrowXPath()
    {
        string outDir = Path.Combine(_root, "xpath");
        Directory.CreateDirectory(outDir);
        var context = new PipelineContext
        {
            AssetOutputDir = outDir,
            GameOutputRoot = outDir,
            AssetLanguage = "none",
            FixDependencies = true,
            ModOpsWrap = true,
        };

        var source = new XmlDocument();
        source.LoadXml("""
            <Assets>
              <Asset>
                <Template>Product</Template>
                <Values><Standard><GUID>1010017</GUID><Name>Child</Name></Standard></Values>
                <BaseAssetGUID>1' or '1</BaseAssetGUID>
              </Asset>
            </Assets>
            """);

        Exception? ex = Record.Exception(() =>
            AssetExtractor.ExtractAssets(context, source, singleGuidFilter: "1010017"));
        Assert.Null(ex);
        Assert.True(Directory.GetFiles(outDir, "*.xml", SearchOption.AllDirectories).Length >= 1);
    }

    [Fact]
    public void GeneratedXmlFootprint_Save_LeavesNoTempFile()
    {
        string outDir = Path.Combine(_root, "footprint");
        Directory.CreateDirectory(outDir);
        var context = new PipelineContext
        {
            AssetOutputDir = outDir,
            GameOutputRoot = outDir,
        };

        var doc = new XmlDocument();
        doc.LoadXml("<Asset><Values><Standard><GUID>9</GUID><Name>Z</Name></Standard></Values></Asset>");
        string path = Path.Combine(outDir, "z.xml");
        GeneratedXmlFootprint.Save(doc, path, context);
        Assert.True(File.Exists(path));
        Assert.Empty(Directory.GetFiles(outDir, "*.tmp"));
        AssertWellFormed(path);
    }

    [Fact]
    public void GeneratedXmlFootprint_Save_DoesNotStartWithBlankLines_AfterPreserveWhitespaceReload()
    {
        string outDir = Path.Combine(_root, "footprint-leading");
        Directory.CreateDirectory(outDir);
        var context = new PipelineContext
        {
            AssetOutputDir = outDir,
            GameOutputRoot = outDir,
            DetectedGameType = "anno1800",
            DetectedGameBuild = new GameBuildInfo(
                "18.4.1412158.165273",
                "Goldmaster",
                "",
                "2026-08-16 12:00:00",
                @"C:\Games\Anno1800\Anno1800.exe"),
        };

        string path = Path.Combine(outDir, "assets.xml");
        var first = new XmlDocument();
        first.LoadXml("""
            <ModOps>
              <ModOp GUID="249947" Type="Replace" Path="/">
                <Asset><Template>Palace</Template></Asset>
              </ModOp>
            </ModOps>
            """);
        GeneratedXmlFootprint.Save(first, path, context);

        // Mod package path loads with PreserveWhitespace=true, then re-applies the footprint.
        var reloaded = new XmlDocument { PreserveWhitespace = true };
        XmlDocumentLoadRetry.Load(reloaded, path);
        GeneratedXmlFootprint.Save(reloaded, path, context);

        string text = File.ReadAllText(path);
        Assert.False(
            text.StartsWith('\n') || text.StartsWith("\r\n", StringComparison.Ordinal),
            "Written XML must not start with blank lines before the header comment.");
        Assert.StartsWith("<!-- Generated by Asset Splitter.", text, StringComparison.Ordinal);

        // Preserve the intentional blank line between the header comment and the root element.
        string normalized = text.Replace("\r\n", "\n", StringComparison.Ordinal);
        Assert.Contains("-->\n\n<ModOps>", normalized, StringComparison.Ordinal);
    }

    [Fact]
    public void XmlDocumentLoadRetry_RejectsDtd()
    {
        string path = Path.Combine(_root, "evil.xml");
        File.WriteAllText(path, """
            <?xml version="1.0"?>
            <!DOCTYPE foo [<!ENTITY xxe SYSTEM "file:///etc/passwd">]>
            <Asset>&xxe;</Asset>
            """);
        var doc = new XmlDocument();
        Assert.ThrowsAny<XmlException>(() => XmlDocumentLoadRetry.Load(doc, path));
    }

    private static void AssertWellFormed(string path)
    {
        var doc = new XmlDocument();
        XmlDocumentLoadRetry.Load(doc, path);
        Assert.NotNull(doc.DocumentElement);
    }
}
